namespace Backends;

interface StorageEngineInterface
{
    /**
     * Check if a storage element exists.
     *
     * @param string $path The path or key of the storage element.
     * @return bool True if the element exists, false otherwise.
     */
    public function exists(string $path): bool;

    /**
     * Get the size of a storage element.
     *
     * @param string $path The path or key of the storage element.
     * @return int|null The size in bytes, or null if the element doesn't exist.
     */
    public function getSize(string $path): ?int;

    /**
     * Remove a storage element.
     *
     * @param string $path The path or key of the storage element.
     * @return bool True on success, false on failure.
     */
    public function remove(string $path): bool;

    /**
     * Open a storage element for reading.
     *
     * @param string $path The path or key of the storage element.
     * @return resource|null A readable stream (the caller closes it), or null on failure.
     */
    public function readStream(string $path);

    /*
     * Staging: an upload is assembled in a staging element, outside every
     * user-visible path, and only appears at its final path once complete
     * and verified. Keys are generated by the application (32 hex digits).
     */

    /**
     * Create an empty staging element.
     */
    public function stagingCreate(string $key): bool;

    /**
     * Write exactly $length bytes from $source at $offset of a staging
     * element. Writing the same range again overwrites it, so a chunk sent
     * twice leaves the same content.
     *
     * @param resource $source A readable stream.
     * @return bool False if the element is missing or fewer bytes were written.
     */
    public function stagingWriteAt(string $key, int $offset, $source, int $length): bool;

    /**
     * Size of a staging element, or null if it doesn't exist.
     */
    public function stagingSize(string $key): ?int;

    /**
     * Open a staging element for reading.
     *
     * @return resource|null A readable stream (the caller closes it), or null on failure.
     */
    public function stagingOpen(string $key);

    /**
     * Move a staging element to its final path. Never replaces an existing
     * element: returns false if $path already exists.
     */
    public function stagingCommit(string $key, string $path): bool;

    /**
     * Remove a staging element. Missing already counts as success.
     */
    public function stagingRemove(string $key): bool;

    /**
     * Bytes free for new data in the storage (staging included), or null if
     * the engine can't tell (uploads are then not checked against it).
     */
    public function freeSpace(): ?int;

    /**
     * Perform a health check to ensure the storage engine is functional.
     *
     * @return bool True if the storage engine is working, false otherwise.
     */
    public function healthCheck(): bool;
}
?>
